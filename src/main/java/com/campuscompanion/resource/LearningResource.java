package com.campuscompanion.resource;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.Instant;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

/**
 * What the database knows about an uploaded PDF. The file itself is in Supabase Storage at {@code
 * storagePath}; its bytes are never stored in the database.
 */
@Entity
@Table(name = "learning_resources")
public class LearningResource {

  @Id
  @GeneratedValue(strategy = GenerationType.IDENTITY)
  private Long id;

  @Column(nullable = false, length = 200)
  private String title;

  @Column(length = 1000)
  private String description;

  @Column(name = "subject_id", nullable = false)
  private Long subjectId;

  /** Null for material that covers the whole subject. */
  @Column(name = "unit_id")
  private Long unitId;

  @Enumerated(EnumType.STRING)
  @Column(name = "resource_type", nullable = false, length = 30)
  private ResourceType resourceType;

  /** Generated by the server. It never contains anything from the uploaded file name. */
  @Column(name = "storage_path", nullable = false, length = 300, updatable = false)
  private String storagePath;

  /** Kept for display only. */
  @Column(name = "original_file_name", nullable = false, length = 255, updatable = false)
  private String originalFileName;

  @Column(name = "mime_type", nullable = false, length = 100, updatable = false)
  private String mimeType;

  @Column(name = "file_size_bytes", nullable = false, updatable = false)
  private long fileSizeBytes;

  @JdbcTypeCode(SqlTypes.CHAR)
  @Column(name = "checksum_sha256", nullable = false, length = 64, updatable = false)
  private String checksumSha256;

  @JdbcTypeCode(SqlTypes.SMALLINT)
  @Column(nullable = false)
  private int version = 1;

  @Enumerated(EnumType.STRING)
  @Column(nullable = false, length = 10)
  private ResourceStatus status = ResourceStatus.PUBLISHED;

  @Column(name = "uploaded_by", nullable = false, updatable = false)
  private Long uploadedBy;

  @Column(name = "created_at", nullable = false, updatable = false)
  private Instant createdAt = Instant.now();

  @Column(name = "updated_at", nullable = false)
  private Instant updatedAt = Instant.now();

  /** Required by JPA. */
  protected LearningResource() {}

  public LearningResource(
      String title,
      String description,
      Long subjectId,
      Long unitId,
      ResourceType resourceType,
      String storagePath,
      String originalFileName,
      long fileSizeBytes,
      String checksumSha256,
      Long uploadedBy) {
    this.storagePath = storagePath;
    this.originalFileName = originalFileName;
    this.mimeType = "application/pdf";
    this.fileSizeBytes = fileSizeBytes;
    this.checksumSha256 = checksumSha256;
    this.uploadedBy = uploadedBy;
    describe(title, description, subjectId, unitId, resourceType, ResourceStatus.PUBLISHED);
  }

  /** Replaces the details an admin may edit. The file itself never changes. */
  public void describe(
      String title,
      String description,
      Long subjectId,
      Long unitId,
      ResourceType resourceType,
      ResourceStatus status) {
    this.title = title;
    this.description = description;
    this.subjectId = subjectId;
    this.unitId = unitId;
    this.resourceType = resourceType;
    this.status = status;
    this.updatedAt = Instant.now();
  }

  public boolean isPublished() {
    return status == ResourceStatus.PUBLISHED;
  }

  public Long getId() {
    return id;
  }

  public String getTitle() {
    return title;
  }

  public String getDescription() {
    return description;
  }

  public Long getSubjectId() {
    return subjectId;
  }

  public Long getUnitId() {
    return unitId;
  }

  public ResourceType getResourceType() {
    return resourceType;
  }

  public String getStoragePath() {
    return storagePath;
  }

  public String getOriginalFileName() {
    return originalFileName;
  }

  public long getFileSizeBytes() {
    return fileSizeBytes;
  }

  public ResourceStatus getStatus() {
    return status;
  }

  public Instant getCreatedAt() {
    return createdAt;
  }
}
